def table(header, rows):
    return '\n'.join(['| '+' | '.join(header)+' |','| '+' | '.join(['---']*len(header))+' |']+
                     ['| '+' | '.join(map(str,row))+' |' for row in rows])+'\n'


def provenance(root,run_id):
    p=json.loads((root/'runs'/run_id/'passport.json').read_text())
    return f"`{run_id}`, исходный HEAD `{p['commit_sha']}`; status **debug**. Exact SHA-256 кода/входов/конфигураций — в `runs/{run_id}/passport.json`."


def active_parameter(name,branch,version,target):
    if name in {'cp_mof','cp_pei','cp_water','epsilon_s','epsilon_d','Q_water','m_W','a_s_ref','alpha_fraction','kappa_fraction'}:return False
    if name=='n_N' and branch!='availability':return False # exact n_N*A0 ridge before clip
    if name in {'h_max','K_h','K_b','Q_b'} and branch!='bicarbonate':return False
    if name=='gamma' and branch not in {'availability','suppression'}:return False
    if name=='xi' and branch!='affinity':return False
    if name=='power' and version!='v1.1-connectivity':return False
    if name=='rho_pei' and version=='v1.1-connectivity':return False
    kind=target[:2]
    if any(other in name for other in ('R1','R2')) and kind not in name:return False
    return True


def priorities(screen):
    first,second=map(str,screen['seeds']);best={}
    for key,b in screen['branches'].items():
        if not key.startswith(first+'/'):continue
        _,version,interpretation,branch,*_=key.split('/')
        repeat=screen['branches'][second+key[len(first):]]
        for target,params in b['rank_correlations'].items():
            for name,r1 in params.items():
                r2=repeat['rank_correlations'].get(target,{}).get(name,0.)
                strength=min(abs(r1),abs(r2))
                if r1*r2<=0 or strength<screen['correlations_selection_threshold'] or not active_parameter(name,branch,version,target):continue
                if strength>best.get(name,(0.,))[0]:best[name]=(strength,r1,r2,key[len(first)+1:],target)
    return sorted(best.items(),key=lambda kv:-kv[1][0])


